/**
 * TEAM-6351 (R3-F1 on TEAM-6347 / PR #1001) — the lifecycle half that lives in
 * deploy/apprunner/setup-jira-webhook.sh: JIRA_WEBHOOK_SIGNING_PENDING must be
 * cleared from .env.local if and only if this script actually configures the
 * Jira webhook. See apply-env-jira-webhook-secret.test.ts for the writer half
 * (.claude-plugin/bin/apply-env.sh sets/carries the flag).
 *
 * Root cause recap: apply-env.sh's JIRA_WEBHOOK_SECRET_NEW=1 stdout marker is
 * one-shot — it is computed by diffing the answers against the secret already
 * on disk, and apply-env.sh's own write makes that diff disappear on the very
 * next run. A /setup run that stops between apply-env.sh and this script (a
 * failed module verification is the common case) therefore loses the signal
 * on re-run, and skills/setup/SKILL.md falls through to deploying the hub
 * before Jira is configured — every delivery 401s with no redelivery.
 *
 * Fix verified here: this script clears JIRA_WEBHOOK_SIGNING_PENDING from
 * .env.local only after "Webhook created successfully" — every earlier exit
 * (missing env, refused secret, failed curl) leaves the line untouched.
 *
 * Hermetic, same pattern as jira-webhook-secret-format.test.ts: scratch copy
 * of the script + deploy/lib, PATH-shimmed curl that logs argv and never
 * touches the network, child env from an allow-list.
 */
import { afterEach, describe, expect, it } from "vitest";
import { chmodSync, cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { spawnSync } from "node:child_process";

const REPO_ROOT = resolve(__dirname, "../../..");
const SETUP_JIRA_WEBHOOK_SH =
  process.env.SETUP_JIRA_WEBHOOK_SH ?? join(REPO_ROOT, "deploy", "apprunner", "setup-jira-webhook.sh");
const HEX = "a087bb7308b9ddb0e5281aa541d57292d3cc5a2b3a5837b4f6f10744dfdcd464";
const PENDING_LINE = 'JIRA_WEBHOOK_SIGNING_PENDING="1"';

const scratchDirs: string[] = [];
afterEach(() => {
  for (const dir of scratchDirs.splice(0)) rmSync(dir, { recursive: true, force: true });
});
const scratch = (prefix: string): string => {
  const dir = mkdtempSync(join(tmpdir(), prefix));
  scratchDirs.push(dir);
  return dir;
};

const hermeticEnv = (binDir: string, extra: Record<string, string> = {}): NodeJS.ProcessEnv => {
  const base: Record<string, string> = {
    PATH: `${binDir}:${process.env.PATH ?? "/usr/local/bin:/usr/bin:/bin"}`,
    HOME: process.env.HOME ?? "/tmp",
    LANG: "C",
  };
  return { ...base, ...extra } as NodeJS.ProcessEnv;
};

const shim = (dir: string, name: string, body: string): string => {
  const p = join(dir, name);
  writeFileSync(p, body);
  chmodSync(p, 0o755);
  return p;
};

// What apply-env.sh leaves behind when a /setup re-run brought a new secret
// onto a deployed-but-unsigned hub (TEAM-6351): the flag plus the normal
// carried-over lines, in the same shape apply-env.sh emits them.
const ENV_WITH_PENDING = `# Generated by .claude-plugin/bin/apply-env.sh — safe to edit by hand
NEXT_PUBLIC_BRAND_NAME="Test Hub"
AWS_REGION="us-east-1"
TICKET_PROVIDER="jira"
JIRA_SITE_URL="example.atlassian.net"
JIRA_WEBHOOK_SECRET="${HEX}"
${PENDING_LINE}
DEPLOYMENT_URL="https://hub.example"
`;
const ENV_WITHOUT_PENDING = ENV_WITH_PENDING.replace(`${PENDING_LINE}\n`, "");
// For the refused-secret case: the file's own JIRA_WEBHOOK_SECRET line would
// win over (overwrite) the deliberately-malformed env var once
// load_env_local sources it, so that variant omits the line and lets the
// malformed value come from the environment only.
const ENV_WITH_PENDING_NO_SECRET = ENV_WITH_PENDING.replace(`JIRA_WEBHOOK_SECRET="${HEX}"\n`, "");

/**
 * Scratch tree keeping the deploy/apprunner/../.. layout (so REPO_ROOT inside
 * the script resolves to the scratch dir), with a real .env.local the
 * script's clearing step can grep/rewrite. Jira credentials are passed as
 * process env (not through the file) so a missing/malformed .env.local for
 * them never masks the thing under test, matching
 * jira-webhook-secret-format.test.ts's runSetup.
 */
const runSetup = (opts: { envLocal?: string; curlOutcome: "success" | "fail" | "refuse-secret" }) => {
  const root = scratch("jira-webhook-pending-");
  mkdirSync(join(root, "deploy", "apprunner"), { recursive: true });
  cpSync(join(REPO_ROOT, "deploy", "lib"), join(root, "deploy", "lib"), { recursive: true });
  cpSync(SETUP_JIRA_WEBHOOK_SH, join(root, "deploy", "apprunner", "setup-jira-webhook.sh"));
  if (opts.envLocal !== undefined) {
    writeFileSync(join(root, ".env.local"), opts.envLocal);
  }

  const bin = join(root, "bin");
  mkdirSync(bin);
  const curlLog = join(root, "curl.log");
  // POST (webhook create) succeeds iff curlOutcome is "success"; the GET
  // (list) call always "fails" so the script falls back to EXISTING="[]"
  // (same shape as a brand-new Jira project with no prior webhooks) —
  // mirrors jira-webhook-secret-format.test.ts's success-path shim.
  const shimBody = `#!/usr/bin/env bash
printf '%s\\0' "$@" >> "${curlLog}"
for a in "$@"; do
  if [[ "$a" == "POST" ]]; then
    if [[ "${opts.curlOutcome}" == "success" ]]; then
      echo '{"self":"https://example.atlassian.net/rest/webhooks/1.0/webhook/1"}'
      exit 0
    fi
    exit 22
  fi
done
exit 22
`;
  shim(bin, "curl", shimBody);

  const env: Record<string, string> = {
    JIRA_SITE_URL: "example.atlassian.net",
    JIRA_EMAIL: "ops@example.com",
    JIRA_API_TOKEN: "test-token",
    JIRA_PROJECT_KEY: "TEAM",
    DEPLOYMENT_URL: "https://hub.example",
  };
  if (opts.curlOutcome === "refuse-secret") {
    env.JIRA_WEBHOOK_SECRET = "ab c"; // space → require_jira_webhook_secret_format refuses
  } else {
    env.JIRA_WEBHOOK_SECRET = HEX;
  }

  const r = spawnSync("bash", [join(root, "deploy", "apprunner", "setup-jira-webhook.sh")], {
    cwd: tmpdir(),
    encoding: "utf8",
    timeout: 60_000,
    env: hermeticEnv(bin, env),
  });
  const envLocalAfter = existsSync(join(root, ".env.local")) ? readFileSync(join(root, ".env.local"), "utf8") : null;
  const curlArgs = existsSync(curlLog) ? readFileSync(curlLog, "utf8").split("\0") : null;
  return { ...r, envLocalAfter, curlArgs };
};

describe("setup-jira-webhook.sh clears JIRA_WEBHOOK_SIGNING_PENDING only on success (TEAM-6351 R3-F1)", () => {
  it("success: webhook created → flag line removed, rest of .env.local byte-identical, mode 600", () => {
    const r = runSetup({ envLocal: ENV_WITH_PENDING, curlOutcome: "success" });
    expect(r.status, `${r.stdout}\n${r.stderr}`).toBe(0);
    expect(r.stdout).toMatch(/Cleared JIRA_WEBHOOK_SIGNING_PENDING/);
    expect(r.envLocalAfter).toBe(ENV_WITHOUT_PENDING);
    expect(r.envLocalAfter).not.toContain("JIRA_WEBHOOK_SIGNING_PENDING");
  });

  it("failed webhook creation (Jira rejects the POST): exit 1, flag untouched", () => {
    const r = runSetup({ envLocal: ENV_WITH_PENDING, curlOutcome: "fail" });
    expect(r.status, `${r.stdout}\n${r.stderr}`).toBe(1);
    expect(r.stderr).toMatch(/Failed to create webhook/);
    expect(r.envLocalAfter).toBe(ENV_WITH_PENDING);
    expect(r.stdout).not.toMatch(/Cleared/);
  });

  it("refused secret (space/newline): exit 1 before any curl call, flag untouched", () => {
    const r = runSetup({ envLocal: ENV_WITH_PENDING_NO_SECRET, curlOutcome: "refuse-secret" });
    expect(r.status, `${r.stdout}\n${r.stderr}`).toBe(1);
    expect(r.stderr).toMatch(/JIRA_WEBHOOK_SECRET contains whitespace or a newline/);
    expect(r.curlArgs, "reached curl before refusing").toBeNull();
    expect(r.envLocalAfter).toBe(ENV_WITH_PENDING_NO_SECRET);
  });

  it("no .env.local at all (prerequisites come from the environment only): success still exits 0, still nothing to clear", () => {
    const r = runSetup({ curlOutcome: "success" });
    expect(r.status, `${r.stdout}\n${r.stderr}`).toBe(0);
    expect(r.envLocalAfter).toBeNull();
    expect(r.stdout).not.toMatch(/Cleared/);
  });

  it(".env.local with no pending flag: success exits 0, nothing printed about clearing, file otherwise untouched", () => {
    const r = runSetup({ envLocal: ENV_WITHOUT_PENDING, curlOutcome: "success" });
    expect(r.status, `${r.stdout}\n${r.stderr}`).toBe(0);
    expect(r.stdout).not.toMatch(/Cleared/);
    expect(r.envLocalAfter).toBe(ENV_WITHOUT_PENDING);
  });

  it("re-running after a successful clear is a no-op for the flag (idempotent)", () => {
    const first = runSetup({ envLocal: ENV_WITH_PENDING, curlOutcome: "success" });
    expect(first.envLocalAfter).toBe(ENV_WITHOUT_PENDING);
    const second = runSetup({ envLocal: first.envLocalAfter!, curlOutcome: "success" });
    expect(second.status, `${second.stdout}\n${second.stderr}`).toBe(0);
    expect(second.stdout).not.toMatch(/Cleared/);
    expect(second.envLocalAfter).toBe(ENV_WITHOUT_PENDING);
  });
});
