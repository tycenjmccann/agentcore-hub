#!/usr/bin/env node
/**
 * docs/workflow/deliverables.md is GENERATED from src/config/workflows.json
 * (`deliverableFamilies` + each def's `deliverables[]`). Run with no args to
 * rewrite it; `--check` exits 1 when the committed doc is stale (CI).
 *
 * The registry is the single source: the board strip, the workflow-output
 * Lambda's writing-standard lint and this page all read it, so the page can
 * never say something the lint does not enforce.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const CONFIG = JSON.parse(readFileSync(resolve(ROOT, "src/config/workflows.json"), "utf8"));
const OUT = resolve(ROOT, "docs/workflow/deliverables.md");

const families = CONFIG.deliverableFamilies || {};
const code = (s) => `\`${s}\``;
const authors = (a) => (Array.isArray(a) ? a : [a]).map((x) => x.replace(/^agentcore_hub_/, "")).join(", ");
const templateOf = (d) => {
  if (d.kind === "pr") return "PR body";
  if (d.kind === "binary") return "n/a";
  if (d.template === null) return "own contract";
  if (d.template && d.template !== families[d.family]?.template) return code(d.template);
  return code(families[d.family]?.template || "");
};

const lines = [];
lines.push("# Deliverables per workflow");
lines.push("");
lines.push("<!-- GENERATED by scripts/gen-deliverables-doc.mjs from src/config/workflows.json. Do not edit by hand. -->");
lines.push("");
lines.push("Every workflow def declares what it owes, per phase, in `src/config/workflows.json` (`deliverables[]`). Three consumers read that one list: this page, the board's artifacts modal (present / missing per deliverable) and the workflow-output Lambda, which refuses a registered markdown deliverable that does not follow its family template ([`blueprints/writing-standard.md`](../../blueprints/writing-standard.md)). Keys are relative to `workflows/<id>/shared/`; `*` is a single-segment glob.");
lines.push("");
lines.push("## Five families, five templates");
lines.push("");
lines.push("A deliverable belongs to one family, chosen by who reads it and what they do next. Each family has one template blueprint (reader questions as the `##` sections, in order, plus one real rewritten example) that every author loads before writing.");
lines.push("");
lines.push("| Family | Written for | Sections (in order) | Template |");
lines.push("|---|---|---|---|");
for (const [name, f] of Object.entries(families)) {
  lines.push(`| ${code(name)} | ${f.reader} | ${f.sections.map((s) => code("## " + s)).join(" ")} | [${f.template}](../../blueprints/${f.template}.md) |`);
}
lines.push("");
lines.push("Rules the lint enforces on every templated markdown deliverable: `# Title` first; the family's `##` sections present, in order, answer first; the lead section is prose of at most 80 words; extra `##` sections only after the template's; no ALL-CAPS heading or label, no `•` bullets. A refusal is returned to the agent with the missing sections and the template to load; nothing is written.");
lines.push("");
lines.push("## Approvals: one standard, the question changes");
lines.push("");
lines.push("Every human gate reads one decision document plus a `review-package-<gate>.json` ping derived from it (`summary` = the document's lead sentence, `bullets` = its attention items, `links` = the document first). The document is a `brief` wherever a human approves work; Spec and Plan Approval read the `spec` itself (its `## Outcome` is the decision line); Counsel Sign-off reads the `external` redlines with the contract review behind them.");
lines.push("");
lines.push("| Gate | Defs | The reader decides | Reads |");
lines.push("|---|---|---|---|");
const gateRows = new Map();
for (const w of CONFIG.workflows) {
  for (const d of w.deliverables || []) {
    if (!d.gate) continue;
    const row = gateRows.get(d.gate) || { defs: new Set(), reads: new Set() };
    row.defs.add(w.id);
    if (d.template !== "review-package") row.reads.add(`${code(d.key)} (${d.family})`);
    gateRows.set(d.gate, row);
  }
}
const QUESTION = {
  "Spec Approval": "Is this the right thing to build?",
  "Plan Approval": "Is this the right way to build it?",
  "Merge Approval": "Does this merge?",
  "Counsel Sign-off": "Do these redlines go to the counterparty?",
  "Operator checkpoint": "Do we keep spending on this run?",
};
for (const [gate, row] of gateRows) {
  lines.push(`| ${gate} | ${[...row.defs].join(", ")} | ${QUESTION[gate] || ""} | ${[...row.reads].join(", ")} |`);
}
lines.push(`| Deploy approval (pipeline ManualApproval, Telegram) | any CD-registered repo | Does this go live? | ${code("cd-evidence/deploy-<sha>.md")} (record) + the merge brief |`);
lines.push("");
lines.push("## Per workflow");
lines.push("");
for (const w of CONFIG.workflows) {
  lines.push(`### ${w.name} (${code(w.id)})`);
  lines.push("");
  lines.push(w.writingStandard
    ? "Writing standard: **enforced** (the Lambda lints every templated markdown deliverable below)."
    : "Writing standard: **listed only**; the lint is off for this def until its blueprints are converted to the templates.");
  lines.push("");
  lines.push("| Phase | Deliverable | Key | Family | Author | Reader | Required | Template | Gate | Notes |");
  lines.push("|---|---|---|---|---|---|---|---|---|---|");
  const order = [];
  for (const p of w.phases) { order.push(p.agentPhase); for (const x of p.extraAgentPhases || []) order.push(x); }
  const rank = (ph) => { const i = order.indexOf(ph); return i < 0 ? 99 : i; };
  const rows = [...(w.deliverables || [])].sort((a, b) => rank(a.phase) - rank(b.phase));
  for (const d of rows) {
    const notes = [d.framework ? `${d.framework} only` : "", d.note || ""].filter(Boolean).join("; ");
    lines.push(`| ${d.phase} | ${d.title} | ${code(d.key)} | ${d.family} | ${authors(d.author)} | ${d.reader} | ${d.required ? "yes" : "no"} | ${templateOf(d)} | ${d.gate || ""} | ${notes} |`);
  }
  lines.push("");
}
lines.push("## Not on this list, on purpose");
lines.push("");
lines.push("- The QA and CI **verdicts** are completion records (`completions/<ticket>.json`, `evidence_kind`, `ci_status`), not files; the evidence folders above are their attachments.");
lines.push("- `plan.md` (operator, playbook) and playbook `spec.md` keep their own exact sections because other blueprints read those headings; they are listed with template \"own contract\" and are not linted.");
lines.push("- Agent-folder copies (`workflows/<id>/<agentId>/...`) are staging; only `shared/` counts.");
lines.push("");
lines.push("## Changing the list");
lines.push("");
lines.push("Edit `deliverables[]` on the def in `src/config/workflows.json`, run `node scripts/gen-deliverables-doc.mjs`, and let `scripts/check-deliverables-parity.sh` tell you which blueprint still has to load the template. A new family needs a `blueprints/template-<family>.md` whose numbered section list matches `deliverableFamilies.<family>.sections` exactly (`src/lib/workflow/deliverables.test.ts` pins it).");
lines.push("");

const text = lines.join("\n");
if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(OUT, "utf8"); } catch { /* missing */ }
  if (current !== text) {
    console.error("docs/workflow/deliverables.md is stale — run: node scripts/gen-deliverables-doc.mjs");
    process.exit(1);
  }
  console.log("docs/workflow/deliverables.md: up to date");
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT} (${text.length} bytes)`);
}
